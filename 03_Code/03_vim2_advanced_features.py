mutation_pattern = re.compile(
    r"^([A-Z])(\d+)([A-Z])$"
)


def extract_mutation_position(
    mutation
):
    """
    Extract the numerical residue position
    from standard mutation notation.

    Example:
    Y67A -> 67
    H114R -> 114
    """

    if pd.isna(mutation):

        return np.nan


    mutation = str(
        mutation
    ).strip()


    match = mutation_pattern.match(
        mutation
    )


    if match:

        return int(
            match.group(2)
        )


    return np.nan


def extract_wild_type_residue(
    mutation
):
    """
    Extract the wild-type amino-acid identity.

    Example:
    Y67A -> Y
    """

    if pd.isna(mutation):

        return np.nan


    mutation = str(
        mutation
    ).strip()


    match = mutation_pattern.match(
        mutation
    )


    if match:

        return match.group(1)


    return np.nan


