# DSSP states:
#
# H = alpha helix
# B = isolated beta bridge
# E = extended beta strand
# G = 3-10 helix
# I = pi helix
# T = hydrogen-bonded turn
# S = bend
# - = other / loop / irregular structure


DSSP_TO_CATEGORY = {

    "H": "Helix",
    "G": "Helix",
    "I": "Helix",

    "E": "Sheet",
    "B": "Sheet",

    "T": "Coil",
    "S": "Coil",
    "-": "Coil"
}


