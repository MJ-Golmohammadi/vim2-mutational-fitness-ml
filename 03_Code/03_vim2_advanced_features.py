def get_secondary_structure(
    residue_position
):
    """
    Return the collapsed DSSP secondary-structure category
    for the corresponding residue position.

    Returns:
        Helix
        Sheet
        Coil
        NaN for unresolved structural positions
    """

    if pd.isna(
        residue_position
    ):

        return np.nan


    residue_position = int(
        residue_position
    )


    return secondary_structure_category.get(
        residue_position,
        np.nan
    )


def get_secondary_structure_code(
    secondary_structure
):
    """
    Convert the interpretable secondary-structure category
    into an auxiliary numerical representation.
    """

    if pd.isna(
        secondary_structure
    ):

        return np.nan


    return SECONDARY_STRUCTURE_CODE.get(
        secondary_structure,
        np.nan
    )


def get_raw_dssp_code(
    residue_position
):
    """
    Return the original DSSP secondary-structure code.

    This auxiliary feature preserves the full DSSP assignment
    before collapsing into Helix, Sheet, and Coil.
    """

    if pd.isna(
        residue_position
    ):

        return np.nan


    residue_position = int(
        residue_position
    )


    return secondary_structure_raw.get(
        residue_position,
        np.nan
    )


