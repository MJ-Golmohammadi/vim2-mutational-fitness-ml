# 12. IDENTIFY THE NEAREST L3 RESIDUE
# ============================================================

def identify_nearest_L3_residue(
    residue_position
):
    """
    Identify the closest L3 residue for each mutation.
    """

    if pd.isna(
        residue_position
    ):

        return np.nan


    residue_position = int(
        residue_position
    )


    if residue_position not in ca_coordinates:

        return np.nan


    mutation_coordinate = (
        ca_coordinates[
            residue_position
        ]
    )


    distance_dict = {}


    for l3_position, l3_coordinate in (
        l3_coordinates.items()
    ):

        distance_dict[
            l3_position
        ] = np.linalg.norm(
            mutation_coordinate -
            l3_coordinate
        )


    return min(
        distance_dict,
        key=distance_dict.get
    )


