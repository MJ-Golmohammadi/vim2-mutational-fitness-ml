    distance_dict = {}


    for metal_position, metal_coordinate in (
        metal_site_coordinates.items()
    ):

        distance_dict[
            metal_position
        ] = np.linalg.norm(
            mutation_coordinate -
            metal_coordinate
        )


    nearest_position = min(
        distance_dict,
        key=distance_dict.get
    )


    return nearest_position


