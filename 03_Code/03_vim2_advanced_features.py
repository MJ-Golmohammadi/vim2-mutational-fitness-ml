# 10. CALCULATE MINIMUM DISTANCE TO THE METAL SITE
# ============================================================

def calculate_distance_to_metal_site(
    residue_position
):
    """
    Calculate the minimum C-alpha distance between one residue
    and the validated VIM-2 metal-binding site.

    Parameters
    ----------
    residue_position : int
        Residue position in VIM-2 numbering.

    Returns
    -------
    float
        Minimum Euclidean distance in Angstroms.

    np.nan
        Returned when the residue is not structurally resolved
        in the 4NQ2 reference structure.
    """

    # Return NaN for missing or invalid positions.
    if pd.isna(residue_position):

        return np.nan


    residue_position = int(
        residue_position
    )


    # Structural coordinates are unavailable for residues that
    # are not resolved in the PDB structure.
    if residue_position not in ca_coordinates:

        return np.nan


    mutation_coordinate = ca_coordinates[
        residue_position
    ]


    # Calculate the distance from the mutated residue to every
    # validated metal-site residue.
    distances = []

    for metal_position, metal_coordinate in (
        metal_site_coordinates.items()
    ):

        distance = np.linalg.norm(
            mutation_coordinate -
            metal_coordinate
        )

        distances.append(
            distance
        )


    # Return the minimum distance to the metal-binding site.
    return float(
        np.min(distances)
    )


