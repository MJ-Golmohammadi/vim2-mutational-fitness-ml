# ============================================================
# 6. PARSE MUTATION POSITIONS
# ============================================================

# Expected mutation format:
# A123V
#
# Group 1 = wild-type amino acid
# Group 2 = residue position
# Group 3 = mutant amino acid

mutation_pattern = re.compile(
    r"^([A-Z])(\d+)([A-Z])$"
)


def extract_mutation_position(mutation):
    """
    Extract the numerical residue position from standard
    single-amino-acid substitution notation.

    Example:
    H114A -> 114
    """

    if pd.isna(mutation):
        return np.nan

    mutation = str(mutation).strip()

    match = mutation_pattern.match(
        mutation
    )

    if match:

        return int(
            match.group(2)
        )

    return np.nan


