# 4. EXTRACT THE WILD-TYPE SEQUENCE FROM THE MUTATION DATASET
# ============================================================

# The mutation dataset contains substitutions in the format:
# X123Y
#
# where:
# X = wild-type amino acid
# 123 = residue position
# Y = mutant amino acid
#
# The wild-type identity at each position is reconstructed
# directly from the validated mutation column.

def parse_mutation(
    mutation
):
    """
    Parse a standard amino-acid substitution.

    Example:
    H114R -> WT='H', Position=114, Mutant='R'
    """

    if pd.isna(mutation):

        return None


    mutation = str(
        mutation
    ).strip()


    match = re.match(
        r"^([A-Z])(\d+)([A-Z])$",
        mutation
    )


    if match is None:

        return None


    return {

        "WT":
            match.group(1),

        "Position":
            int(
                match.group(2)
            ),

        "Mutant":
            match.group(3)
    }


