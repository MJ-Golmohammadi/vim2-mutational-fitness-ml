# 6. PARSE MUTATION POSITIONS
# ============================================================

mutation_pattern = re.compile(
    r"^([A-Z])(\d+)([A-Z])$"
)


def extract_mutation_position(
    mutation
):
    """
    Extract the numerical residue position from standard
    amino-acid substitution notation.

    Example:
    Y67A -> 67
    H114R -> 114
    """

    if pd.isna(mutation):

        return np.nan


    mutation = str(
        mutation
    ).strip()


    match = mutation_pattern.match(
        mutation
    )


    if match:

        return int(
            match.group(2)
        )


    return np.nan


