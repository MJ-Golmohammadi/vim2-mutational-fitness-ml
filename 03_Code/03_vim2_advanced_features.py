# ============================================================
# 7. DEFINE THE LOCAL WINDOW EXTRACTION FUNCTION
# ============================================================

def get_local_window(
    sequence,
    position,
    radius
):
    """
    Extract the available local sequence window centered on
    the specified 1-based residue position.

    No artificial padding is introduced at sequence boundaries.

    Example with radius = 5:
    Up to 5 residues upstream
    + central residue
    + up to 5 residues downstream
    """

    sequence_length = len(
        sequence
    )


    zero_based_index = (
        position - 1
    )


    start_index = max(
        0,
        zero_based_index - radius
    )


    end_index = min(
        sequence_length,
        zero_based_index + radius + 1
    )


    return sequence[
        start_index:end_index
    ]


# ============================================================
# 8. DEFINE SHANNON ENTROPY CALCULATION
# ============================================================

def calculate_shannon_entropy(
    sequence_window
):
    """
    Calculate Shannon entropy for amino-acid composition
    within a local sequence window.

    Higher entropy indicates a more compositionally diverse
    local environment.

    Lower entropy indicates a more compositionally repetitive
    local environment.
    """

    if len(sequence_window) == 0:

        return np.nan


    residue_counts = pd.Series(
        list(sequence_window)
    ).value_counts()


    probabilities = (

        residue_counts
        /
        residue_counts.sum()
    )


    entropy = -np.sum(

        probabilities
        *
        np.log2(
            probabilities
        )
    )


    return entropy


