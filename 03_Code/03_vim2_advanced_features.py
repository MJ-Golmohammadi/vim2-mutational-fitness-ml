# 11. CALCULATE DISTANCE TO L10
# ============================================================

def calculate_distance_to_L10(
    residue_position
):
    """
    Calculate the minimum C-alpha distance between
    a mutation position and the validated L10 loop.

    Distance unit:
    Angstroms (Å)

    NaN:
    Returned when the mutated residue does not have
    resolved structural coordinates in 4NQ2.
    """

    if pd.isna(
        residue_position
    ):

        return np.nan


    residue_position = int(
        residue_position
    )


    if residue_position not in ca_coordinates:

        return np.nan


    mutation_coordinate = (
        ca_coordinates[
            residue_position
        ]
    )


    distances = []


    for l10_position, l10_coordinate in (
        l10_coordinates.items()
    ):

        distance = np.linalg.norm(
            mutation_coordinate -
            l10_coordinate
        )


        distances.append(
            distance
        )


    return float(
        np.min(
            distances
        )
    )


