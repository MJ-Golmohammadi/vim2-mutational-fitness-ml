# 12. IDENTIFY NEAREST L10 RESIDUE
# ============================================================

def identify_nearest_L10_residue(
    residue_position
):
    """
    Identify the closest validated L10 residue
    for each mutation position.
    """

    if pd.isna(
        residue_position
    ):

        return np.nan


    residue_position = int(
        residue_position
    )


    if residue_position not in ca_coordinates:

        return np.nan


    mutation_coordinate = (
        ca_coordinates[
            residue_position
        ]
    )


    distance_dict = {}


    for l10_position, l10_coordinate in (
        l10_coordinates.items()
    ):

        distance_dict[
            l10_position
        ] = np.linalg.norm(
            mutation_coordinate -
            l10_coordinate
        )


    return min(
        distance_dict,
        key=distance_dict.get
    )


