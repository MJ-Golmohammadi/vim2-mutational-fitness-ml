    if chain_id != TARGET_CHAIN:

        continue


    # Standard residue numbering.
    #
    # residue_id format:
    # (' ', residue_number, insertion_code)

    if residue_id[0] != " ":

        continue


    residue_position = residue_id[1]


    dssp_record = dssp[
        dssp_key
    ]


    # DSSP tuple index 2 contains the secondary-structure code.
    dssp_code = dssp_record[2]


    # DSSP may occasionally return a blank-like value.
    # Standardize such cases as irregular/coil structure.
    if (
        dssp_code is None
        or str(dssp_code).strip() == ""
    ):

        dssp_code = "-"


    dssp_code = str(
        dssp_code
    ).strip()


    if dssp_code not in DSSP_TO_CATEGORY:

        dssp_code = "-"


    secondary_structure_raw[
        residue_position
    ] = dssp_code


    secondary_structure_category[
        residue_position
    ] = DSSP_TO_CATEGORY[
        dssp_code
    ]


    # DSSP tuple index 1 contains the amino-acid identity.
    pdb_residue_identity[
        residue_position
    ] = dssp_record[1]


