def calculate_distance_to_L3(
    residue_position
):
    """
    Calculate the minimum C-alpha distance between
    a mutation position and the validated L3 loop.

    Distance is reported in Angstroms (Å).

    NaN is returned when the mutated residue does not
    have resolved coordinates in the reference structure.
    """

    if pd.isna(
        residue_position
    ):

        return np.nan


    residue_position = int(
        residue_position
    )


    # No structural coordinate -> no distance.
    if residue_position not in ca_coordinates:

        return np.nan


    mutation_coordinate = (
        ca_coordinates[
            residue_position
        ]
    )


    distances = []


    for l3_position, l3_coordinate in (
        l3_coordinates.items()
    ):

        distance = np.linalg.norm(
            mutation_coordinate -
            l3_coordinate
        )


        distances.append(
            distance
        )


    return float(
        np.min(
            distances
        )
    )


