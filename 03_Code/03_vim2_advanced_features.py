# 13. NCBI EFETCH FUNCTION
# ================================================================
#
# EFetch retrieves FASTA records corresponding to Protein IDs.
#
# NCBI recommends batching large requests rather than sending an
# extremely large list in one request.
# ================================================================

def ncbi_efetch_fasta(
    ids,
    batch_size=200
):

    all_records = []

    for start in range(
        0,
        len(ids),
        batch_size
    ):

        batch = ids[
            start:start + batch_size
        ]

        params = {
            "db": "protein",
            "id": ",".join(batch),
            "rettype": "fasta",
            "retmode": "text",
            "email": NCBI_EMAIL
        }

        response = requests.get(
            f"{NCBI_BASE}/efetch.fcgi",
            params=params,
            timeout=120
        )

        response.raise_for_status()

        fasta_text = response.text

        records = list(
            SeqIO.parse(
                StringIO(fasta_text),
                "fasta"
            )
        )

        all_records.extend(records)

        print(
            f"Retrieved batch "
            f"{start + 1}–"
            f"{min(start + batch_size, len(ids))} "
            f"/ {len(ids)}"
        )

        time.sleep(
            REQUEST_DELAY
        )

    return all_records


