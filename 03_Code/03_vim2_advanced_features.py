def ncbi_esearch(
    query,
    retmax=10000
):

    params = {
        "db": "protein",
        "term": query,
        "retmode": "json",
        "retmax": retmax,
        "email": NCBI_EMAIL
    }

    response = requests.get(
        f"{NCBI_BASE}/esearch.fcgi",
        params=params,
        timeout=60
    )

    response.raise_for_status()

    result = response.json()

    return result["esearchresult"]["idlist"]


