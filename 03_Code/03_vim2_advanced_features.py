# Expected mutation format:
# Example: R205T
# Wild-type residue = R
# Position = 205
# Mutant residue = T

mutation_pattern = re.compile(
    r"^([A-Z])(\d+)([A-Z])$"
)


parsed_mutations = []

for mutation in df[mutation_column].dropna().astype(str):

    match = mutation_pattern.match(
        mutation.strip()
    )

    if match:

        wt_residue = match.group(1)
        position = int(match.group(2))
        mutant_residue = match.group(3)

        parsed_mutations.append(
            {
                "Mutation": mutation,
                "WT_Residue": wt_residue,
                "Position": position,
                "Mutant_Residue": mutant_residue
            }
        )


mutation_info = pd.DataFrame(
    parsed_mutations
)


