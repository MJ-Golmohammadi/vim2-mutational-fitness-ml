def safe_xlim(values, margin=0.08):
    values = np.asarray(values, dtype=float)
    finite = values[np.isfinite(values)]
    if len(finite) == 0:
        return (-1.0, 1.0)
    lo = float(np.min(finite))
    hi = float(np.max(finite))
    span = max(hi - lo, 0.2)
    return lo - margin * span, hi + margin * span


